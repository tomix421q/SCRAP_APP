import { beforeEach, describe, expect, it, vi } from 'vitest';

// Prisma is fully mocked: these tests must never touch a real database.
const prismaMock = vi.hoisted(() => ({
	labelGroup: { findMany: vi.fn(), findUnique: vi.fn() },
	operator: { findUnique: vi.fn() },
	user: { findUnique: vi.fn() },
	scrapRecord: { createMany: vi.fn(), findFirst: vi.fn() }
}));

vi.mock('@/server/prisma', () => ({ default: prismaMock }));

import { actions } from '../src/routes/(Client)/scandmclabel/+page.server';

const dmcLabel = {
	id: 1,
	code: 'ABC*',
	groups: [
		{
			id: 10,
			qadIdentity: 'QAD1',
			isRebuild: true,
			materials: [{ material: 'PN-10' }],
			scrapCodes: [{ code: 'S1' }, { code: 'S9', isOtherComponent: true }]
		},
		{
			id: 11,
			qadIdentity: 'QAD1',
			isRebuild: false,
			materials: [{ material: 'PN-11' }],
			scrapCodes: [{ code: 'S2' }]
		}
	]
};

const quantityLabel = {
	id: 2,
	code: 'QNT-SCRAP-L1',
	groups: [
		{ id: 20, isRebuild: false, materials: [], scrapCodes: [] },
		{ id: 21, isRebuild: false, materials: [], scrapCodes: [] }
	]
};

function row(groupId: number, extra: Record<string, unknown> = {}) {
	return { groupId, groupName: `Group ${groupId}`, ...extra };
}

function formRequest(action: string, fields: Record<string, string>) {
	const body = new FormData();
	for (const [key, value] of Object.entries(fields)) body.set(key, value);
	return new Request(`http://localhost/scandmclabel?/${action}`, { method: 'POST', body });
}

function saveScrap(fields: Record<string, string>) {
	return actions.saveScrap({ request: formRequest('saveScrap', fields) } as never);
}

function saveQuantityScrap(fields: Record<string, string>) {
	return actions.saveQuantityScrap({ request: formRequest('saveQuantityScrap', fields) } as never);
}

const scrapFields = {
	dmc: 'ABC123',
	isRebuild: 'false',
	operator: '4321',
	scrapPayload: JSON.stringify([
		row(10, { selectedScrapCode: 'S1' }),
		row(11, { selectedScrapCode: 'S2' })
	])
};

const rebuildFields = {
	...scrapFields,
	isRebuild: 'true',
	scrapPayload: JSON.stringify([
		row(10, { selectedScrapCode: 'S1' }),
		row(11, { isOtherComponent: true, otherComponentCauseGroupId: 10 })
	])
};

const quantityFields = {
	dmc: 'QNT-SCRAP-L1',
	labelGroupId: '2',
	operator: '4321',
	scrapPayload: JSON.stringify([
		row(20, { selectedScrapCode: 'Q1', quantity: 3 }),
		row(21, { selectedScrapCode: 'Q2', quantity: 5 })
	])
};

/** `payloadRecId` of every record written by the n-th `createMany` call. */
function savedPayloadIds(call = 0): unknown[] {
	const { data } = prismaMock.scrapRecord.createMany.mock.calls[call][0];
	return data.map((record: { payloadRecId?: unknown }) => record.payloadRecId);
}

beforeEach(() => {
	vi.clearAllMocks();
	prismaMock.labelGroup.findMany.mockResolvedValue([dmcLabel]);
	prismaMock.labelGroup.findUnique.mockResolvedValue(quantityLabel);
	prismaMock.operator.findUnique.mockResolvedValue({ fullName: 'Test Operator' });
	prismaMock.user.findUnique.mockResolvedValue(null);
	prismaMock.scrapRecord.createMany.mockResolvedValue({ count: 2 });
	// No earlier rebuild saved under the scanned DMC
	prismaMock.scrapRecord.findFirst.mockResolvedValue(null);
});

describe.each([
	['scrap', () => saveScrap(scrapFields)],
	['rebuild', () => saveScrap(rebuildFields)],
	['quantity scrap', () => saveQuantityScrap(quantityFields)]
])('payloadRecId on %s save', (_mode, save) => {
	it('gives every record of one save the same non-empty payload ID', async () => {
		await save();

		const ids = savedPayloadIds();
		expect(ids).toHaveLength(2);
		expect(typeof ids[0]).toBe('string');
		expect(ids[0]).not.toBe('');
		expect(ids[1]).toBe(ids[0]);
	});

	it('gives a repeated save of the same label a new payload ID', async () => {
		await save();
		await save();

		expect(savedPayloadIds(1)[0]).not.toBe(savedPayloadIds(0)[0]);
	});
});

describe('payloadRecId is generated by the server only', () => {
	it('ignores a payload ID sent in the scrap form', async () => {
		await saveScrap({ ...scrapFields, payloadRecId: 'client-value' });
		expect(savedPayloadIds()).not.toContain('client-value');
	});

	it('ignores a payload ID sent in the quantity scrap form', async () => {
		await saveQuantityScrap({ ...quantityFields, payloadRecId: 'client-value' });
		expect(savedPayloadIds()).not.toContain('client-value');
	});
});

describe('a failed save writes no records', () => {
	it.each([
		[
			'scrap with an unknown part group',
			() =>
				saveScrap({
					...scrapFields,
					scrapPayload: JSON.stringify([row(99, { selectedScrapCode: 'S1' })])
				})
		],
		['scrap with an empty DMC', () => saveScrap({ ...scrapFields, dmc: '' })],
		['scrap with an empty payload', () => saveScrap({ ...scrapFields, scrapPayload: '' })],
		[
			'quantity scrap with an invalid operator',
			() => saveQuantityScrap({ ...quantityFields, operator: 'abc' })
		]
	])('%s', async (_case, save) => {
		const result = await save();
		expect(result).toMatchObject({ status: 400 });
		expect(prismaMock.scrapRecord.createMany).not.toHaveBeenCalled();
	});

	it.each([
		['scrap', () => saveScrap(scrapFields)],
		['quantity scrap', () => saveQuantityScrap(quantityFields)]
	])('%s with an unverified card', async (_mode, save) => {
		prismaMock.operator.findUnique.mockResolvedValue(null);
		const result = await save();
		expect(result).toMatchObject({ status: 403 });
		expect(prismaMock.scrapRecord.createMany).not.toHaveBeenCalled();
	});
});
